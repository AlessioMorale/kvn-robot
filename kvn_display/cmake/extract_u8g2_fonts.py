"""Copies the named fonts out of u8g2's u8g2_fonts.c into a small C file.

u8g2_fonts.c holds every u8g2 font (about 40 MB of C); compiling only the fonts the screen uses
keeps the build fast on the robot. Each font keeps the comment block above it (name, copyright).

    extract_u8g2_fonts.py <u8g2_fonts.c> <output.c> <font name>...
"""

import re
import sys


def extract(source: str, names: list[str]) -> str:
    lines = source.splitlines()
    blocks = []
    for name in names:
        start = next(
            (i for i, line in enumerate(lines) if line.startswith(f"const uint8_t {name}[")), None
        )
        if start is None:
            raise SystemExit(f"{name} not found in u8g2_fonts.c")
        # The comment block directly above the definition
        comment = start
        if comment > 0 and lines[comment - 1].strip() == "*/":
            while comment > 0 and not lines[comment - 1].startswith("/*"):
                comment -= 1
            comment -= 1
        end = start
        while not re.search(r'";\s*$', lines[end]):
            end += 1
        blocks.append("\n".join(lines[comment : end + 1]))
    return (
        "/* Generated by extract_u8g2_fonts.py from u8g2_fonts.c: only the fonts kvn_display uses. */\n"
        '#include "u8g2.h"\n\n' + "\n\n".join(blocks) + "\n"
    )


def main() -> None:
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding="latin-1") as stream:
        source = stream.read()
    output = extract(source, sys.argv[3:])
    with open(sys.argv[2], "w", encoding="latin-1") as stream:
        stream.write(output)


if __name__ == "__main__":
    main()
